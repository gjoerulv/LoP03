# Crystal Dungeons — the music note tables (single source of truth).
# Dot-sourced by generate_audio.ps1 (chiptune WAV renderer) and
# generate_midi.ps1 (Standard MIDI File exporter), so the shipped WAVs and
# the editable .mid files can never drift apart.
#
# Each song: bpm, beats (total length; the WAV renderer sizes the buffer from
# it), a square lead and a triangle bass, each a sequence of @(note, beats)
# steps ("A4" names, '-' = rest). `jingle` marks the one-shot tracks (no loop
# markers in the MIDI). The M32 town-ladder variants derive from the town
# entry via $TownVariants (semitone shift, tempo multiplier, lead wave/amp;
# variant bass is always tri at 0.28).
#
# Extended arrangements (owner-directed, 2026-08-08): every song grew from
# its original 16-beat loop into a sectioned form on the classic game-loop
# pattern — A (the original tune, verbatim) / B (new, same key and scale) /
# breakdown or interlude (texture drop) / A again (literal repeat) / where it
# fits, a turnaround that resolves into the loop seam. Sections are named
# variables and reused by reference, so a repeat IS the same notes. Beat
# counts are annotated per section; lead and bass sections of the same name
# always sum to the same beats.

